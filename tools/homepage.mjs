import { execFileSync } from 'node:child_process'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

const root = fileURLToPath(new URL('../', import.meta.url))
const check = process.argv.includes('--check')
const begin = '<!-- SOLAR-PUBLISHED-PLUGINS:START -->'
const end = '<!-- SOLAR-PUBLISHED-PLUGINS:END -->'
const tags = execFileSync('git', ['tag', '--list', '@lisihao/dsh-solar-*@*'], { cwd: root, encoding: 'utf8' }).trim().split('\n').filter(Boolean)
const releases = new Map()
for (const tag of tags) {
  const match = /^(@lisihao\/dsh-solar-([a-z0-9-]+))@(\d+)\.(\d+)\.(\d+)$/.exec(tag)
  if (!match) continue
  const [, name, directory, major, minor, patch] = match
  const metadata = JSON.parse(execFileSync('git', ['show', `${tag}:plugins/${directory}/package.json`], { cwd: root, encoding: 'utf8' }))
  const version = `${major}.${minor}.${patch}`
  if (metadata.name !== name || metadata.version !== version) throw new Error(`Release tag/package mismatch: ${tag}`)
  const current = releases.get(name)
  const parts = [major, minor, patch].map(Number)
  const newer = !current || parts.findIndex((value, index) => value !== current.parts[index]) >= 0
    && parts[parts.findIndex((value, index) => value !== current.parts[index])] > current.parts[parts.findIndex((value, index) => value !== current.parts[index])]
  if (newer) releases.set(name, { ...metadata, parts })
}
const section = releases.size === 0
  ? 'No stable Solar market release has been published. Preview tarballs and maintained forks are available in [the curated package directory](distribution/plugins/); they are separate from market publication.'
  : '| Plugin | Description | Released version | Installation |\n|---|---|---|---|\n' + [...releases.values()].sort((a, b) => a.name.localeCompare(b.name)).map(plugin => `| ${plugin.name} | ${plugin.description.replaceAll('|', '\\|')} | ${plugin.version} | See [market guide](docs/market-guide.md). |`).join('\n')
const path = join(root, 'README.md')
const current = await readFile(path, 'utf8')
const block = `${begin}\n${section}\n${end}`
const next = current.includes(begin)
  ? current.slice(0, current.indexOf(begin)) + block + current.slice(current.indexOf(end) + end.length)
  : current.trimEnd() + '\n\n## Published plugins\n\n' + block + '\n'
const guide = '# Solar plugin market guide\n\nGenerated by `pnpm homepage` from released plugin tags.\n\n' + (releases.size
  ? 'Published plugins are listed on the [homepage](../README.md#published-plugins). Market publication and its HTTPS index URL require separate release acceptance.\n'
  : 'No stable Solar market release or market index has been published. There is no index URL to add in Discover. User-authorized preview tarballs and maintained forks are distributed through [the curated package directory](../distribution/plugins/). Use the [installation guide](curated-plugin-installation.md); direct package downloads do not publish a market index. Source candidates remain under `incubator/`.\n')
let currentGuide = ''
try { currentGuide = await readFile(join(root, 'docs/market-guide.md'), 'utf8') } catch (error) { if (error.code !== 'ENOENT') throw error }
if (check) {
  if (current !== next || currentGuide !== guide) throw new Error('Homepage/market guide is stale; run pnpm homepage.')
  console.log('Homepage and market guide match released tags.')
} else {
  await writeFile(path, next)
  await writeFile(join(root, 'docs/market-guide.md'), guide)
}
